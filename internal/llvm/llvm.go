// Package llvm lowers the residual IR to textual LLVM IR.
package llvm

import (
	_ "embed"
	"fmt"
	"math"
	"strings"

	"apus/internal/ir"
)

// Runtime is the C support library that must be linked with emitted modules.
//
//go:embed rt_c.txt
var Runtime string

type gen struct {
	p      *ir.Program
	b      strings.Builder
	allocs strings.Builder
	globs  strings.Builder
	nt     int
	nl     int
	term   bool
	nstr   int
	ncnt   int
}

// Emit renders p as an LLVM module. triple may be empty.
func Emit(p *ir.Program, triple string) string {
	g := &gen{p: p}
	g.term = false
	for i := 0; i < p.NVars; i++ {
		fmt.Fprintf(&g.allocs, "  %%v%d = alloca i64\n  store i64 0, ptr %%v%d\n", i, i)
	}
	for i, a := range p.Arrs {
		fmt.Fprintf(&g.allocs, "  %%a%d = alloca [%d x i%d]\n", i, a.N, a.Ty.Bits)
	}
	for i, c := range p.Bufs {
		fmt.Fprintf(&g.allocs, "  %%b%d = alloca [%d x i8]\n", i, c)
	}
	for i, t := range p.Tables {
		g.table(i, t)
	}
	for i, a := range p.Arenas {
		fmt.Fprintf(&g.globs, "@arena_top_%d = internal global i64 0\n@arena_mem_%d = internal global [%d x i8] zeroinitializer ; %s\n", i, i, a.Size, a.Name)
	}
	g.block(p.Body)
	if !g.term {
		g.ret(ir.Ret{})
	}
	var out strings.Builder
	out.WriteString("; Generated by the Apus compiler\n")
	if triple != "" {
		fmt.Fprintf(&out, "target triple = %q\n", triple)
	}
	out.WriteString(`declare void @apus_write(ptr, i64)
declare void @apus_write_dec(i64, i32)
declare i64 @apus_read_line(ptr, i64)
declare i64 @apus_read_int(i32, i32)
declare i32 @apus_memeq(ptr, ptr, i64)
declare i64 @apus_fmt_dec(ptr, i64, i32)
declare i64 @apus_fmt_f64(ptr, i64, i32)
declare void @apus_write_f64(i64, i32)
declare i64 @apus_read_f64(i32)
declare double @llvm.sqrt.f64(double)
declare float @llvm.sqrt.f32(float)
declare double @llvm.floor.f64(double)
declare float @llvm.floor.f32(float)
declare double @llvm.ceil.f64(double)
declare float @llvm.ceil.f32(float)
declare double @llvm.trunc.f64(double)
declare float @llvm.trunc.f32(float)
declare double @llvm.fabs.f64(double)
declare float @llvm.fabs.f32(float)
declare void @apus_trap(i32) noreturn
declare void @apus_flush()
declare void @llvm.memcpy.p0.p0.i64(ptr, ptr, i64, i1)
declare {i64, i1} @llvm.sadd.with.overflow.i64(i64, i64)
declare {i64, i1} @llvm.ssub.with.overflow.i64(i64, i64)
declare {i64, i1} @llvm.smul.with.overflow.i64(i64, i64)
declare {i64, i1} @llvm.uadd.with.overflow.i64(i64, i64)
declare {i64, i1} @llvm.usub.with.overflow.i64(i64, i64)
declare {i64, i1} @llvm.umul.with.overflow.i64(i64, i64)
`)
	out.WriteString(g.globs.String())
	out.WriteString("\ndefine i32 @main() {\nentry:\n")
	out.WriteString(g.allocs.String())
	out.WriteString("  br label %body\nbody:\n")
	out.WriteString(g.b.String())
	out.WriteString("}\n")
	return out.String()
}

func (g *gen) tmp() string {
	g.nt++
	return fmt.Sprintf("%%t%d", g.nt)
}
func (g *gen) lbl(prefix string) string {
	g.nl++
	return fmt.Sprintf("%s%d", prefix, g.nl)
}

func (g *gen) line(f string, a ...any) {
	if g.term {
		g.label(g.lbl("dead"))
	}
	fmt.Fprintf(&g.b, "  "+f+"\n", a...)
}
func (g *gen) label(name string) {
	fmt.Fprintf(&g.b, "%s:\n", name)
	g.term = false
}
func (g *gen) br(l string) {
	if g.term {
		return
	}
	fmt.Fprintf(&g.b, "  br label %%%s\n", l)
	g.term = true
}
func (g *gen) brCond(c, t, f string) {
	g.line("br i1 %s, label %%%s, label %%%s", c, t, f)
	g.term = true
}

func imm(c uint64) string { return fmt.Sprintf("%d", int64(c)) }

// val returns an i64 value expression for an operand.
func (g *gen) val(o ir.Operand) string {
	if o.Const {
		return imm(o.C)
	}
	t := g.tmp()
	g.line("%s = load i64, ptr %%v%d", t, o.Var)
	return t
}

func (g *gen) store(dst int, v string) { g.line("store i64 %s, ptr %%v%d", v, dst) }

func (g *gen) trapIf(cond string, code ir.TrapCode) {
	tl, cl := g.lbl("trap"), g.lbl("cont")
	g.brCond(cond, tl, cl)
	g.label(tl)
	g.line("call void @apus_trap(i32 %d)", int(code))
	g.line("unreachable")
	g.term = true
	g.label(cl)
}

func (g *gen) icmp(pred, a, b string) string {
	t := g.tmp()
	g.line("%s = icmp %s i64 %s, %s", t, pred, a, b)
	return t
}
func (g *gen) or1(a, b string) string {
	t := g.tmp()
	g.line("%s = or i1 %s, %s", t, a, b)
	return t
}

func (g *gen) rangeCheck(r string, t ir.IntTy, code ir.TrapCode) {
	if t.Bits >= 64 {
		return
	}
	if t.Signed {
		lo := g.icmp("slt", r, imm(uint64(t.MinS())))
		hi := g.icmp("sgt", r, imm(uint64(t.MaxS())))
		g.trapIf(g.or1(lo, hi), code)
	} else {
		g.trapIf(g.icmp("ugt", r, imm(t.MaxU())), code)
	}
}

func (g *gen) canon(r string, t ir.IntTy) string {
	if t.Bits >= 64 {
		return r
	}
	if t.Signed {
		sh := 64 - t.Bits
		a, b := g.tmp(), g.tmp()
		g.line("%s = shl i64 %s, %d", a, r, sh)
		g.line("%s = ashr i64 %s, %d", b, a, sh)
		return b
	}
	a := g.tmp()
	g.line("%s = and i64 %s, %d", a, r, int64(t.MaxU()))
	return a
}

func (g *gen) block(b []ir.Inst) {
	for _, in := range b {
		g.inst(in)
	}
}

func (g *gen) inst(in ir.Inst) {
	switch s := in.(type) {
	case ir.Mov:
		g.store(s.Dst, g.val(s.A))
	case ir.Bin:
		g.bin(s)
	case ir.Neg:
		a := g.val(s.A)
		if s.Check {
			g.trapIf(g.icmp("eq", a, imm(uint64(s.Ty.MinS()))), ir.TrapOverflow)
		}
		t := g.tmp()
		g.line("%s = sub i64 0, %s", t, a)
		g.store(s.Dst, t)
	case ir.Not:
		t := g.tmp()
		g.line("%s = xor i64 %s, 1", t, g.val(s.A))
		g.store(s.Dst, t)
	case ir.Cast:
		g.cast(s)
	case ir.Clamp:
		g.clamp(s)
	case ir.Load:
		idx := g.val(s.Idx)
		n := g.p.Arrs[s.Arr].N
		if s.Check {
			g.trapIf(g.icmp("uge", idx, fmt.Sprint(n)), ir.TrapIndex)
		}
		ptr, raw := g.tmp(), g.tmp()
		at := g.p.Arrs[s.Arr].Ty
		g.line("%s = getelementptr inbounds [%d x i%d], ptr %%a%d, i64 0, i64 %s", ptr, n, at.Bits, s.Arr, idx)
		g.line("%s = load i%d, ptr %s", raw, at.Bits, ptr)
		g.store(s.Dst, g.widen(raw, at))
	case ir.Store:
		idx := g.val(s.Idx)
		v := g.val(s.A)
		n := g.p.Arrs[s.Arr].N
		if s.Check {
			g.trapIf(g.icmp("uge", idx, fmt.Sprint(n)), ir.TrapIndex)
		}
		ptr := g.tmp()
		at := g.p.Arrs[s.Arr].Ty
		g.line("%s = getelementptr inbounds [%d x i%d], ptr %%a%d, i64 0, i64 %s", ptr, n, at.Bits, s.Arr, idx)
		g.line("store i%d %s, ptr %s", at.Bits, g.narrow(v, at), ptr)
	case ir.ArrInit:
		n := g.p.Arrs[s.Arr].N
		at := g.p.Arrs[s.Arr].Ty
		for i, o := range s.Vals {
			v := g.val(o)
			ptr := g.tmp()
			g.line("%s = getelementptr inbounds [%d x i%d], ptr %%a%d, i64 0, i64 %d", ptr, n, at.Bits, s.Arr, i)
			g.line("store i%d %s, ptr %s", at.Bits, g.narrow(v, at), ptr)
		}
	case ir.TLoad:
		idx := g.val(s.Idx)
		n := len(g.p.Tables[s.Tab].Vals)
		ty := g.p.Tables[s.Tab].Ty
		if s.Check {
			g.trapIf(g.icmp("uge", idx, fmt.Sprint(n)), ir.TrapIndex)
		}
		ptr, raw := g.tmp(), g.tmp()
		g.line("%s = getelementptr inbounds [%d x i%d], ptr @tab%d, i64 0, i64 %s", ptr, n, ty.Bits, s.Tab, idx)
		g.line("%s = load i%d, ptr %s", raw, ty.Bits, ptr)
		g.store(s.Dst, g.widen(raw, ty))
	case ir.BufLoad:
		idx, ln := g.val(s.Idx), g.val(s.Len)
		g.trapIf(g.icmp("uge", idx, ln), ir.TrapIndex)
		ptr, raw, z := g.tmp(), g.tmp(), g.tmp()
		g.line("%s = getelementptr inbounds [%d x i8], ptr %%b%d, i64 0, i64 %s", ptr, g.p.Bufs[s.Buf], s.Buf, idx)
		g.line("%s = load i8, ptr %s", raw, ptr)
		g.line("%s = zext i8 %s to i64", z, raw)
		g.store(s.Dst, z)
	case ir.StrEq:
		g.strEq(s)
	case ir.FBin:
		g.fbin(s)
	case ir.FUn:
		g.fun(s)
	case ir.FCvt:
		g.fcvt(s)
	case ir.WriteFloat:
		sg := 0
		if s.F32 {
			sg = 1
		}
		g.line("call void @apus_write_f64(i64 %s, i32 %d)", g.val(s.A), sg)
	case ir.ReadFloat:
		t := g.tmp()
		sg := 0
		if s.F32 {
			sg = 1
		}
		g.line("%s = call i64 @apus_read_f64(i32 %d)", t, sg)
		g.store(s.Dst, t)
	case ir.StrBuild:
		g.strBuild(s)
	case ir.BufEq:
		g.bufEq(s)
	case ir.ArrFill:
		g.fill(s)
	case ir.ArrCopy:
		a := g.p.Arrs[s.Dst]
		g.line("call void @llvm.memcpy.p0.p0.i64(ptr %%a%d, ptr %%a%d, i64 %d, i1 false)", s.Dst, s.Src, a.N*a.Ty.Bits/8)
	case ir.ReadLine:
		t := g.tmp()
		g.line("%s = call i64 @apus_read_line(ptr %%b%d, i64 %d)", t, s.Buf, s.Cap)
		g.store(s.Len, t)
	case ir.ReadInt:
		t := g.tmp()
		sg := 0
		if s.Ty.Signed {
			sg = 1
		}
		g.line("%s = call i64 @apus_read_int(i32 %d, i32 %d)", t, s.Ty.Bits, sg)
		g.store(s.Dst, t)
	case ir.WriteStr:
		name := fmt.Sprintf("@.str%d", g.nstr)
		g.nstr++
		fmt.Fprintf(&g.globs, "%s = private unnamed_addr constant [%d x i8] c\"%s\"\n", name, len(s.S), escape(s.S))
		g.line("call void @apus_write(ptr %s, i64 %d)", name, len(s.S))
	case ir.WriteBuf:
		g.line("call void @apus_write(ptr %%b%d, i64 %s)", s.Buf, g.val(s.Len))
	case ir.WriteDec:
		sg := 0
		if s.Ty.Signed {
			sg = 1
		}
		g.line("call void @apus_write_dec(i64 %s, i32 %d)", g.val(s.A), sg)
	case ir.Alloc:
		top, nw := g.tmp(), g.tmp()
		size := g.val(s.Size)
		g.line("%s = load i64, ptr @arena_top_%d", top, s.Arena)
		g.line("%s = add i64 %s, %s", nw, top, size)
		g.line("store i64 %s, ptr @arena_top_%d", nw, s.Arena)
		g.store(s.Dst, top)
	case ir.Mark:
		t := g.tmp()
		g.line("%s = load i64, ptr @arena_top_%d", t, s.Arena)
		g.store(s.Slot, t)
	case ir.Reset:
		t := g.tmp()
		g.line("%s = load i64, ptr %%v%d", t, s.Slot)
		g.line("store i64 %s, ptr @arena_top_%d", t, s.Arena)
	case ir.If:
		c := g.icmp("ne", g.val(s.Cond), "0")
		tl, el, end := g.lbl("then"), g.lbl("else"), g.lbl("endif")
		if len(s.Else) == 0 {
			g.brCond(c, tl, end)
		} else {
			g.brCond(c, tl, el)
		}
		g.label(tl)
		g.block(s.Then)
		g.br(end)
		if len(s.Else) > 0 {
			g.label(el)
			g.block(s.Else)
			g.br(end)
		}
		g.label(end)
	case ir.While:
		g.loop(s)
	case ir.Ret:
		g.ret(s)
	case ir.Trap:
		g.line("call void @apus_trap(i32 %d)", int(s.Code))
		g.line("unreachable")
		g.term = true
	default:
		panic(fmt.Sprintf("llvm: unhandled instruction %T", in))
	}
}

// table emits a read-only constant table as a private global.
func (g *gen) table(i int, t ir.Table) {
	if t.Ty.Bits == 8 {
		var raw strings.Builder
		for _, v := range t.Vals {
			fmt.Fprintf(&raw, "\\%02X", byte(v))
		}
		fmt.Fprintf(&g.globs, "@tab%d = private unnamed_addr constant [%d x i8] c\"%s\"\n", i, len(t.Vals), raw.String())
		return
	}
	var parts []string
	for _, v := range t.Vals {
		parts = append(parts, fmt.Sprintf("i%d %d", t.Ty.Bits, truncSigned(v, t.Ty.Bits)))
	}
	fmt.Fprintf(&g.globs, "@tab%d = private unnamed_addr constant [%d x i%d] [%s]\n", i, len(t.Vals), t.Ty.Bits, strings.Join(parts, ", "))
}

func truncSigned(v uint64, bits int) int64 {
	if bits >= 64 {
		return int64(v)
	}
	sh := uint(64 - bits)
	return int64(v<<sh) >> sh
}

// strBuild concatenates parts into a buffer, tracking the write position in the Len variable.
func (g *gen) strBuild(s ir.StrBuild) {
	g.store(s.Len, "0")
	capacity := g.p.Bufs[s.Buf]
	for _, q := range s.Parts {
		pos, dst, n := g.tmp(), g.tmp(), g.tmp()
		g.line("%s = load i64, ptr %%v%d", pos, s.Len)
		g.line("%s = getelementptr inbounds [%d x i8], ptr %%b%d, i64 0, i64 %s", dst, capacity, s.Buf, pos)
		switch q.Kind {
		case 0:
			name := fmt.Sprintf("@.str%d", g.nstr)
			g.nstr++
			fmt.Fprintf(&g.globs, "%s = private unnamed_addr constant [%d x i8] c\"%s\"\n", name, len(q.S), escape(q.S))
			g.line("call void @llvm.memcpy.p0.p0.i64(ptr %s, ptr %s, i64 %d, i1 false)", dst, name, len(q.S))
			g.line("%s = add i64 %s, %d", n, pos, len(q.S))
		case 1:
			ln := g.val(q.Len)
			g.line("call void @llvm.memcpy.p0.p0.i64(ptr %s, ptr %%b%d, i64 %s, i1 false)", dst, q.Buf, ln)
			g.line("%s = add i64 %s, %s", n, pos, ln)
		case 3:
			sg := 0
			if q.F32 {
				sg = 1
			}
			w := g.tmp()
			g.line("%s = call i64 @apus_fmt_f64(ptr %s, i64 %s, i32 %d)", w, dst, g.val(q.A), sg)
			g.line("%s = add i64 %s, %s", n, pos, w)
		default:
			sg := 0
			if q.Ty.Signed {
				sg = 1
			}
			w := g.tmp()
			g.line("%s = call i64 @apus_fmt_dec(ptr %s, i64 %s, i32 %d)", w, dst, g.val(q.A), sg)
			g.line("%s = add i64 %s, %s", n, pos, w)
		}
		g.store(s.Len, n)
	}
}

// bufEq compares two runtime strings: lengths first, then bytes.
func (g *gen) bufEq(s ir.BufEq) {
	la, lb := g.val(s.LenA), g.val(s.LenB)
	g.store(s.Dst, "0")
	cmp, end := g.lbl("beqcmp"), g.lbl("beqend")
	g.brCond(g.icmp("eq", la, lb), cmp, end)
	g.label(cmp)
	r, b, z := g.tmp(), g.tmp(), g.tmp()
	g.line("%s = call i32 @apus_memeq(ptr %%b%d, ptr %%b%d, i64 %s)", r, s.BufA, s.BufB, la)
	g.line("%s = icmp ne i32 %s, 0", b, r)
	g.line("%s = zext i1 %s to i64", z, b)
	g.store(s.Dst, z)
	g.br(end)
	g.label(end)
}

// strEq lowers a comparison against a constant string.
func (g *gen) strEq(s ir.StrEq) {
	ln := g.val(s.Len)
	g.store(s.Dst, "0")
	name := fmt.Sprintf("@.str%d", g.nstr)
	g.nstr++
	fmt.Fprintf(&g.globs, "%s = private unnamed_addr constant [%d x i8] c\"%s\"\n", name, len(s.S), escape(s.S))
	cmp, end := g.lbl("seqcmp"), g.lbl("seqend")
	g.brCond(g.icmp("eq", ln, fmt.Sprint(len(s.S))), cmp, end)
	g.label(cmp)
	r, b, z := g.tmp(), g.tmp(), g.tmp()
	g.line("%s = call i32 @apus_memeq(ptr %%b%d, ptr %s, i64 %d)", r, s.Buf, name, len(s.S))
	g.line("%s = icmp ne i32 %s, 0", b, r)
	g.line("%s = zext i1 %s to i64", z, b)
	g.store(s.Dst, z)
	g.br(end)
	g.label(end)
}

// ---- floating point (values are IEEE bit patterns in the i64 slots)

func ftype(f32 bool) string {
	if f32 {
		return "float"
	}
	return "double"
}

func fsfx(f32 bool) string {
	if f32 {
		return "f32"
	}
	return "f64"
}

// toF turns an i64 slot value into an SSA float/double.
func (g *gen) toF(v string, f32 bool) string {
	if !f32 {
		t := g.tmp()
		g.line("%s = bitcast i64 %s to double", t, v)
		return t
	}
	a, b := g.tmp(), g.tmp()
	g.line("%s = trunc i64 %s to i32", a, v)
	g.line("%s = bitcast i32 %s to float", b, a)
	return b
}

// fromF turns an SSA float/double back into the canonical i64 slot value.
func (g *gen) fromF(f string, f32 bool) string {
	if !f32 {
		t := g.tmp()
		g.line("%s = bitcast double %s to i64", t, f)
		return t
	}
	a, b := g.tmp(), g.tmp()
	g.line("%s = bitcast float %s to i32", a, f)
	g.line("%s = zext i32 %s to i64", b, a)
	return b
}

func (g *gen) fbin(s ir.FBin) {
	ty := ftype(s.F32)
	a, b := g.toF(g.val(s.A), s.F32), g.toF(g.val(s.B), s.F32)
	if s.Op.IsCmp() {
		pred := map[ir.FOp]string{ir.FEq: "oeq", ir.FNe: "une", ir.FLt: "olt", ir.FLe: "ole", ir.FGt: "ogt", ir.FGe: "oge"}[s.Op]
		c, z := g.tmp(), g.tmp()
		g.line("%s = fcmp %s %s %s, %s", c, pred, ty, a, b)
		g.line("%s = zext i1 %s to i64", z, c)
		g.store(s.Dst, z)
		return
	}
	var r string
	switch s.Op {
	case ir.FMin, ir.FMax:
		pred := "olt"
		if s.Op == ir.FMax {
			pred = "ogt"
		}
		c := g.tmp()
		r = g.tmp()
		g.line("%s = fcmp %s %s %s, %s", c, pred, ty, b, a)
		g.line("%s = select i1 %s, %s %s, %s %s", r, c, ty, b, ty, a)
	default:
		inst := map[ir.FOp]string{ir.FAdd: "fadd", ir.FSub: "fsub", ir.FMul: "fmul", ir.FDiv: "fdiv"}[s.Op]
		r = g.tmp()
		g.line("%s = %s %s %s, %s", r, inst, ty, a, b)
	}
	g.store(s.Dst, g.fromF(r, s.F32))
}

func (g *gen) fun(s ir.FUn) {
	ty := ftype(s.F32)
	x := g.toF(g.val(s.A), s.F32)
	if s.Op == ir.FIsNan {
		c, z := g.tmp(), g.tmp()
		g.line("%s = fcmp uno %s %s, %s", c, ty, x, x)
		g.line("%s = zext i1 %s to i64", z, c)
		g.store(s.Dst, z)
		return
	}
	r := g.tmp()
	switch s.Op {
	case ir.FNeg:
		g.line("%s = fneg %s %s", r, ty, x)
	default:
		name := map[ir.FUOp]string{ir.FSqrt: "sqrt", ir.FFloor: "floor", ir.FCeil: "ceil", ir.FTrunc: "trunc", ir.FAbs: "fabs"}[s.Op]
		g.line("%s = call %s @llvm.%s.%s(%s %s)", r, ty, name, fsfx(s.F32), ty, x)
	}
	g.store(s.Dst, g.fromF(r, s.F32))
}

func hexDouble(f float64) string { return fmt.Sprintf("0x%016X", math.Float64bits(f)) }

func (g *gen) fcvt(s ir.FCvt) {
	a := g.val(s.A)
	switch s.Kind {
	case ir.CvtIntToFloat:
		op := "uitofp"
		if s.Int.Signed {
			op = "sitofp"
		}
		r := g.tmp()
		g.line("%s = %s i64 %s to %s", r, op, a, ftype(s.F32))
		g.store(s.Dst, g.fromF(r, s.F32))
	case ir.CvtFloatToFloat: // s.F32 is the source width
		x := g.toF(a, s.F32)
		r := g.tmp()
		if s.F32 {
			g.line("%s = fpext float %s to double", r, x)
		} else {
			g.line("%s = fptrunc double %s to float", r, x)
		}
		g.store(s.Dst, g.fromF(r, !s.F32))
	default: // float -> int, trapping when NaN or outside the target range after truncation
		x := g.toF(a, s.F32)
		if s.F32 {
			w := g.tmp()
			g.line("%s = fpext float %s to double", w, x)
			x = w
		}
		t := g.tmp()
		g.line("%s = call double @llvm.trunc.f64(double %s)", t, x)
		hi := math.Ldexp(1, s.Int.Bits)
		lo := 0.0
		if s.Int.Signed {
			hi = math.Ldexp(1, s.Int.Bits-1)
			lo = -hi
		}
		c1, c2, ok, bad := g.tmp(), g.tmp(), g.tmp(), g.tmp()
		g.line("%s = fcmp oge double %s, %s", c1, t, hexDouble(lo))
		g.line("%s = fcmp olt double %s, %s", c2, t, hexDouble(hi))
		g.line("%s = and i1 %s, %s", ok, c1, c2)
		g.line("%s = xor i1 %s, true", bad, ok)
		g.trapIf(bad, ir.TrapOverflow)
		op := "fptoui"
		if s.Int.Signed {
			op = "fptosi"
		}
		r := g.tmp()
		g.line("%s = %s double %s to i64", r, op, t)
		g.store(s.Dst, r)
	}
}

// narrow truncates an i64 value to the array element width.
func (g *gen) narrow(v string, t ir.IntTy) string {
	if t.Bits >= 64 {
		return v
	}
	r := g.tmp()
	g.line("%s = trunc i64 %s to i%d", r, v, t.Bits)
	return r
}

// widen extends a loaded element back to the canonical i64 representation.
func (g *gen) widen(v string, t ir.IntTy) string {
	if t.Bits >= 64 {
		return v
	}
	r := g.tmp()
	op := "zext"
	if t.Signed {
		op = "sext"
	}
	g.line("%s = %s i%d %s to i64", r, op, t.Bits, v)
	return r
}

// fill emits a loop storing one value into every element of an array.
func (g *gen) fill(s ir.ArrFill) {
	n := g.p.Arrs[s.Arr].N
	v := g.val(s.Val)
	g.ncnt++
	cnt := fmt.Sprintf("%%fcnt%d", g.ncnt)
	fmt.Fprintf(&g.allocs, "  %s = alloca i64\n", cnt)
	g.line("store i64 0, ptr %s", cnt)
	head, body, done := g.lbl("fhead"), g.lbl("fbody"), g.lbl("fdone")
	g.br(head)
	g.label(head)
	i := g.tmp()
	g.line("%s = load i64, ptr %s", i, cnt)
	g.brCond(g.icmp("ult", i, fmt.Sprint(n)), body, done)
	g.label(body)
	ptr, i1 := g.tmp(), g.tmp()
	at := g.p.Arrs[s.Arr].Ty
	g.line("%s = getelementptr inbounds [%d x i%d], ptr %%a%d, i64 0, i64 %s", ptr, n, at.Bits, s.Arr, i)
	g.line("store i%d %s, ptr %s", at.Bits, g.narrow(v, at), ptr)
	g.line("%s = add i64 %s, 1", i1, i)
	g.line("store i64 %s, ptr %s", i1, cnt)
	g.br(head)
	g.label(done)
}

func (g *gen) ret(s ir.Ret) {
	v := "0"
	if s.Has {
		x := g.val(s.A)
		t := g.tmp()
		g.line("%s = trunc i64 %s to i32", t, x)
		v = t
	}
	g.line("call void @apus_flush()")
	g.line("ret i32 %s", v)
	g.term = true
}

func (g *gen) loop(s ir.While) {
	var cnt string
	pre, body, exit := g.lbl("lpre"), g.lbl("lbody"), g.lbl("lexit")
	if s.Bound >= 0 {
		g.ncnt++
		cnt = fmt.Sprintf("%%cnt%d", g.ncnt)
		fmt.Fprintf(&g.allocs, "  %s = alloca i64\n", cnt)
		g.line("store i64 0, ptr %s", cnt)
	}
	g.br(pre)
	g.label(pre)
	g.block(s.Pre)
	c := g.icmp("ne", g.val(s.Cond), "0")
	g.brCond(c, body, exit)
	g.label(body)
	if s.Bound >= 0 {
		n := g.tmp()
		g.line("%s = load i64, ptr %s", n, cnt)
		g.trapIf(g.icmp("uge", n, fmt.Sprint(s.Bound)), ir.TrapBound)
	}
	g.block(s.Body)
	if s.Bound >= 0 && !g.term {
		n, n1 := g.tmp(), g.tmp()
		g.line("%s = load i64, ptr %s", n, cnt)
		g.line("%s = add i64 %s, 1", n1, n)
		g.line("store i64 %s, ptr %s", n1, cnt)
	}
	g.br(pre)
	g.label(exit)
}

func (g *gen) cmpPred(op ir.Op, signed bool) string {
	p := map[ir.Op]string{ir.Eq: "eq", ir.Ne: "ne", ir.Lt: "lt", ir.Le: "le", ir.Gt: "gt", ir.Ge: "ge"}[op]
	if op == ir.Eq || op == ir.Ne {
		return p
	}
	if signed {
		return "s" + p
	}
	return "u" + p
}

func (g *gen) bin(s ir.Bin) {
	a, b := g.val(s.A), g.val(s.B)
	t := s.Ty
	var r string
	switch {
	case s.Op.IsCmp():
		c := g.icmp(g.cmpPred(s.Op, t.Signed), a, b)
		r = g.tmp()
		g.line("%s = zext i1 %s to i64", r, c)
	case s.Op == ir.Min || s.Op == ir.Max:
		pred := map[bool]string{true: "slt", false: "ult"}[t.Signed]
		if s.Op == ir.Max {
			pred = map[bool]string{true: "sgt", false: "ugt"}[t.Signed]
		}
		c := g.icmp(pred, a, b)
		r = g.tmp()
		g.line("%s = select i1 %s, i64 %s, i64 %s", r, c, a, b)
	case s.Op == ir.And || s.Op == ir.Or || s.Op == ir.Xor:
		r = g.tmp()
		g.line("%s = %s i64 %s, %s", r, s.Op, a, b)
	case s.Op == ir.Shl || s.Op == ir.Shr:
		if s.Check {
			g.trapIf(g.icmp("uge", b, fmt.Sprint(t.Bits)), ir.TrapShift)
		}
		r = g.tmp()
		switch {
		case s.Op == ir.Shl:
			g.line("%s = shl i64 %s, %s", r, a, b)
			r = g.canon(r, t)
		case t.Signed:
			g.line("%s = ashr i64 %s, %s", r, a, b)
		default:
			g.line("%s = lshr i64 %s, %s", r, a, b)
		}
	case s.Op == ir.Add || s.Op == ir.Sub || s.Op == ir.Mul:
		name := map[ir.Op]string{ir.Add: "add", ir.Sub: "sub", ir.Mul: "mul"}[s.Op]
		if s.Check && t.Bits >= 64 {
			pre := "u"
			if t.Signed {
				pre = "s"
			}
			agg, v, o := g.tmp(), g.tmp(), g.tmp()
			g.line("%s = call {i64, i1} @llvm.%s%s.with.overflow.i64(i64 %s, i64 %s)", agg, pre, name, a, b)
			g.line("%s = extractvalue {i64, i1} %s, 0", v, agg)
			g.line("%s = extractvalue {i64, i1} %s, 1", o, agg)
			g.trapIf(o, ir.TrapOverflow)
			r = v
		} else {
			r = g.tmp()
			g.line("%s = %s i64 %s, %s", r, name, a, b)
			if s.Check {
				g.rangeCheck(r, t, ir.TrapOverflow)
			}
		}
	default: // Div, Rem
		if s.Check {
			g.trapIf(g.icmp("eq", b, "0"), ir.TrapDivZero)
			if t.Signed {
				if t.Bits >= 64 {
					c1 := g.icmp("eq", a, imm(uint64(t.MinS())))
					c2 := g.icmp("eq", b, "-1")
					both := g.tmp()
					g.line("%s = and i1 %s, %s", both, c1, c2)
					g.trapIf(both, ir.TrapOverflow)
				}
			}
		}
		r = g.tmp()
		inst := map[bool]map[ir.Op]string{
			true:  {ir.Div: "sdiv", ir.Rem: "srem"},
			false: {ir.Div: "udiv", ir.Rem: "urem"},
		}[t.Signed][s.Op]
		g.line("%s = %s i64 %s, %s", r, inst, a, b)
		if s.Check && t.Signed && s.Op == ir.Div {
			g.rangeCheck(r, t, ir.TrapOverflow)
		}
	}
	g.store(s.Dst, r)
}

func (g *gen) cast(s ir.Cast) {
	x := g.val(s.A)
	f, to := s.From, s.To
	var bad string
	switch {
	case f.Signed && to.Signed:
		if to.Bits < 64 {
			bad = g.or1(g.icmp("slt", x, imm(uint64(to.MinS()))), g.icmp("sgt", x, imm(uint64(to.MaxS()))))
		}
	case f.Signed && !to.Signed:
		neg := g.icmp("slt", x, "0")
		bad = neg
		if to.Bits < 64 {
			bad = g.or1(neg, g.icmp("ugt", x, imm(to.MaxU())))
		}
	case !f.Signed && to.Signed:
		bad = g.icmp("ugt", x, imm(uint64(to.MaxS())))
	default:
		if to.Bits < 64 {
			bad = g.icmp("ugt", x, imm(to.MaxU()))
		}
	}
	if bad != "" {
		g.trapIf(bad, ir.TrapOverflow)
	}
	g.store(s.Dst, x)
}

func (g *gen) clamp(s ir.Clamp) {
	v, lo, hi := g.val(s.A), g.val(s.Lo), g.val(s.Hi)
	bp, ap := "ult", "ugt"
	if s.Ty.Signed {
		bp, ap = "slt", "sgt"
	}
	below := g.icmp(bp, v, lo)
	above := g.icmp(ap, v, hi)
	if s.TrapMode {
		g.trapIf(g.or1(below, above), ir.TrapRequire)
		g.store(s.Dst, v)
		return
	}
	t1, t2 := g.tmp(), g.tmp()
	g.line("%s = select i1 %s, i64 %s, i64 %s", t1, below, lo, v)
	g.line("%s = select i1 %s, i64 %s, i64 %s", t2, above, hi, t1)
	g.store(s.Dst, t2)
}

func escape(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c >= 32 && c < 127 && c != '"' && c != '\\' {
			b.WriteByte(c)
		} else {
			fmt.Fprintf(&b, "\\%02X", c)
		}
	}
	return b.String()
}

